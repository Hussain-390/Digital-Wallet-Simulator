package service;

import model.Transaction;

import java.io.BufferedReader;
import java.io.File;
import java.io.FileReader;
import java.io.IOException;
import java.net.URI;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.net.http.HttpTimeoutException;
import java.nio.charset.StandardCharsets;
import java.time.Duration;
import java.util.List;

/**
 * Service class responsible for interfacing with the Gemini Developer API
 * to generate personalized financial insights based on user transaction history.
 */
public class AIService {

    // Store the API key as a constant that can be easily replaced.
    // To avoid hardcoding credentials in source control, this is loaded from
    // the .env file or the environment variable GEMINI_API_KEY.
    private static final String GEMINI_API_KEY = "YOUR_API_KEY_HERE";
    private static final String[] CANDIDATE_MODELS = {
            "gemini-3.1-flash-lite",
            "gemini-3.8-flash",
            "gemini-flash-latest"
    };

    /**
     * Resolves the API key from the .env file, environment variable GEMINI_API_KEY,
     * or fallback to the configured constant.
     *
     * @return the resolved API key
     */
    private static String getApiKey() {
        String[] envPaths = {".env", "../.env", "../../.env", "src/.env", "app/.env", "Digital_Wallet_Simulator-main/.env"};
        for (String path : envPaths) {
            File envFile = new File(path);
            if (envFile.exists() && envFile.isFile()) {
                try (BufferedReader reader = new BufferedReader(new FileReader(envFile))) {
                    String line;
                    while ((line = reader.readLine()) != null) {
                        line = line.trim();
                        if (line.isEmpty() || line.startsWith("#")) {
                            continue;
                        }
                        if (line.startsWith("GEMINI_API_KEY=")) {
                            String value = line.substring("GEMINI_API_KEY=".length()).trim();
                            if ((value.startsWith("\"") && value.endsWith("\"")) ||
                                (value.startsWith("'") && value.endsWith("'"))) {
                                value = value.substring(1, value.length() - 1).trim();
                            }
                            if (!value.isEmpty()) {
                                return value;
                            }
                        }
                    }
                } catch (IOException ignored) {
                }
            }
        }

        String envKey = System.getenv("GEMINI_API_KEY");
        if (envKey != null && !envKey.trim().isEmpty()) {
            return envKey.trim();
        }
        return GEMINI_API_KEY;
    }

    /**
     * Sends the transaction history to the Gemini Developer API and returns financial insights.
     *
     * @param transactions the list of transactions for the user
     * @return the financial insights generated by the AI
     * @throws IllegalStateException if the API key is missing or not configured
     * @throws IOException if network communication fails
     * @throws InterruptedException if the network request is interrupted
     */
    public static String getFinancialInsights(List<Transaction> transactions) throws IOException, InterruptedException {
        String apiKey = getApiKey();
        if (apiKey == null || apiKey.trim().isEmpty() || "YOUR_API_KEY_HERE".equals(apiKey)) {
            throw new IllegalStateException("Gemini API key is missing. Please configure it in .env, service/AIService.java, or set the GEMINI_API_KEY environment variable.");
        }

        if (transactions == null || transactions.isEmpty()) {
            throw new IllegalArgumentException("No transactions available for analysis.");
        }

        // 1. Convert transaction list to readable text
        StringBuilder txHistoryBuilder = new StringBuilder();
        for (Transaction tx : transactions) {
            txHistoryBuilder.append(tx.toString()).append("\n");
        }
        String txHistoryText = txHistoryBuilder.toString();

        // 2. Build prompt for Gemini
        String prompt =
                "You are an AI Financial Assistant integrated into a Digital Wallet application.\n\n"
            + "The following transaction history belongs to ONE user's digital wallet.\n"
            + "Assume the user has only one wallet account.\n"
            + "Do not assume the existence of bank accounts, credit cards, loans, investments, salaries, or other financial products.\n"
            + "Base your analysis ONLY on the wallet transaction history provided.\n\n"
            + "Provide:\n"
            + "• Spending pattern\n"
            + "• Wallet usage behaviour\n"
            + "• Saving suggestion based only on wallet activity\n"
            + "• Any unusual transaction pattern (if present)\n"
            + "• One practical recommendation to improve wallet usage\n\n"
            + "Rules:\n"
            + "- Maximum 6 bullet points.\n"
            + "- Keep the response concise.\n"
            + "- Do not repeat information.\n"
            + "- Do not calculate totals unless they are obvious.\n"
            + "- Do not assume anything outside the provided transactions.\n"
            + "- If there are fewer than 10 transactions, mention that the analysis is based on limited wallet activity.\n"
            + "- Use Rs. for currency amounts.\n\n"
            + "Transaction History:\n\n"
            + txHistoryText;

        // 3. Format the JSON Request Body
        String escapedPrompt = escapeJson(prompt);
        String jsonRequest = "{\"contents\":[{\"parts\":[{\"text\":\"" + escapedPrompt + "\"}]}]}";

        // 4. Create and configure Java HttpClient
        HttpClient client = HttpClient.newBuilder()
                .connectTimeout(Duration.ofSeconds(10))
                .build();

        // 5. Try candidate models in order until one succeeds
        Exception lastException = null;
        for (String model : CANDIDATE_MODELS) {
            String apiUrl = "https://generativelanguage.googleapis.com/v1beta/models/" + model + ":generateContent?key=" + apiKey;
            HttpRequest request = HttpRequest.newBuilder()
                    .uri(URI.create(apiUrl))
                    .header("Content-Type", "application/json")
                    .timeout(Duration.ofSeconds(30))
                    .POST(HttpRequest.BodyPublishers.ofString(jsonRequest, StandardCharsets.UTF_8))
                    .build();

            try {
                HttpResponse<String> response = client.send(request, HttpResponse.BodyHandlers.ofString());
                if (response.statusCode() == 200) {
                    return parseJsonText(response.body());
                } else if (response.statusCode() == 400 || response.statusCode() == 403) {
                    throw new IOException("API request failed (Status " + response.statusCode() + "). Please check if your API key is valid.");
                } else if (response.statusCode() == 404 || response.statusCode() == 500 || response.statusCode() == 503) {
                    lastException = new IOException("Model " + model + " unavailable (Status " + response.statusCode() + ").");
                    continue;
                } else {
                    lastException = new IOException("API request failed with HTTP Status: " + response.statusCode() + "\nResponse: " + response.body());
                }
            } catch (HttpTimeoutException e) {
                lastException = e;
            } catch (IOException e) {
                if (e.getMessage() != null && (e.getMessage().contains("Status 400") || e.getMessage().contains("Status 403"))) {
                    throw e;
                }
                lastException = e;
            }
        }

        if (lastException instanceof HttpTimeoutException) {
            throw (HttpTimeoutException) lastException;
        } else if (lastException instanceof IOException) {
            throw (IOException) lastException;
        } else {
            throw new IOException("Unable to reach Gemini API. Please check your network connection and API key.");
        }
    }

    /**
     * Escapes special characters in string to make it JSON-safe.
     *
     * @param value the raw text to escape
     * @return the escaped JSON-safe text
     */
    private static String escapeJson(String value) {
        if (value == null) {
            return "";
        }
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < value.length(); i++) {
            char ch = value.charAt(i);
            switch (ch) {
                case '"':
                    sb.append("\\\"");
                    break;
                case '\\':
                    sb.append("\\\\");
                    break;
                case '\b':
                    sb.append("\\b");
                    break;
                case '\f':
                    sb.append("\\f");
                    break;
                case '\n':
                    sb.append("\\n");
                    break;
                case '\r':
                    sb.append("\\r");
                    break;
                case '\t':
                    sb.append("\\t");
                    break;
                default:
                    if (ch < ' ') {
                        String hex = Integer.toHexString(ch);
                        sb.append("\\u").append("0".repeat(4 - hex.length())).append(hex);
                    } else {
                        sb.append(ch);
                    }
            }
        }
        return sb.toString();
    }

    /**
     * Parses the Gemini JSON response manually to extract the response text
     * without introducing external dependencies.
     *
     * @param json the raw JSON string response from the Gemini API
     * @return the extracted text content
     * @throws IOException if parsing fails or structure doesn't match
     */
    private static String parseJsonText(String json) throws IOException {
        try {
            StringBuilder fullText = new StringBuilder();
            int searchPos = 0;
            while (true) {
                int keyIndex = json.indexOf("\"text\"", searchPos);
                if (keyIndex == -1) {
                    break;
                }
                int colonIndex = json.indexOf(":", keyIndex);
                if (colonIndex == -1) break;
                int startQuote = json.indexOf("\"", colonIndex);
                if (startQuote == -1) break;

                StringBuilder sb = new StringBuilder();
                boolean escaped = false;
                int endQuote = -1;
                for (int i = startQuote + 1; i < json.length(); i++) {
                    char c = json.charAt(i);
                    if (escaped) {
                        switch (c) {
                            case 'n': sb.append('\n'); break;
                            case 't': sb.append('\t'); break;
                            case 'r': sb.append('\r'); break;
                            case 'b': sb.append('\b'); break;
                            case 'f': sb.append('\f'); break;
                            case '"': sb.append('"'); break;
                            case '\\': sb.append('\\'); break;
                            case '/': sb.append('/'); break;
                            case 'u':
                                if (i + 4 < json.length()) {
                                    String hex = json.substring(i + 1, i + 5);
                                    sb.append((char) Integer.parseInt(hex, 16));
                                    i += 4;
                                }
                                break;
                            default: sb.append(c);
                        }
                        escaped = false;
                    } else if (c == '\\') {
                        escaped = true;
                    } else if (c == '"') {
                        endQuote = i;
                        break;
                    } else {
                        sb.append(c);
                    }
                }

                if (endQuote != -1) {
                    if (fullText.length() > 0) {
                        fullText.append("\n");
                    }
                    fullText.append(sb);
                    searchPos = endQuote + 1;
                } else {
                    break;
                }
            }

            if (fullText.length() == 0) {
                throw new IOException("Failed to parse Gemini response: 'text' field not found.");
            }
            return fullText.toString();
        } catch (Exception e) {
            throw new IOException("Invalid API response format: " + e.getMessage(), e);
        }
    }
}
